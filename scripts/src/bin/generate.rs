use ahash::RandomState;
use roxmltree::Document as XmlDocument;
use std::{ fs, mem };
use std::collections::{ BTreeMap, HashMap };
use std::iter::repeat;
use std::io::{ BufWriter, Write as _ };
use std::path::PathBuf;

const ROOT: &str = "phosphor-core/assets";

// run in `/scripts` dir

fn main() {
	let mut root_dir = PathBuf::new();
	root_dir.push("..");
	root_dir.push(ROOT);

	let mut styles = fs::read_dir(&root_dir)
		.unwrap()
		.map(|dirent| dirent.unwrap().file_name().to_str().unwrap().to_string())
		.collect::<Vec<_>>();
	styles.sort_unstable();

	let entries = styles.iter()
		.map(|style| {
			let style = &**style;
			let mut dir_path = PathBuf::from(&root_dir);
			dir_path.push(style);
			(style, dir_path)
		})
		.flat_map(|(style, dir_path)| {
			let suffix = if style == "regular" { ".svg".into() } else { format!("-{style}.svg") };
			let mut icons = fs::read_dir(dir_path).unwrap()
				.map(|ent| ent.unwrap().file_name().to_str().unwrap().to_string())
				.map(|filename| filename.strip_suffix(&suffix).unwrap().into())
				.collect::<Vec<String>>();
			icons.sort();
			repeat(style)
				.zip(icons)
				.zip(repeat(suffix))
				.map(|((style, icon), suffix)| (style, icon, suffix))
		})
		.collect::<Vec<_>>();

	let grouped_by_style = {
		let mut grouped = HashMap::<_, Vec<_>, _>::with_hasher(RandomState::new());

		for (style, icon, suffix) in &entries {
			let entry = grouped
				.entry(*style)
				.or_default();
			entry.push((&**icon, &**suffix));
		}

		grouped
	};

	let grouped_by_icon = {
		let mut grouped = HashMap::<_, Vec<_>, _>::with_hasher(RandomState::new());

		for (style, icon, suffix) in &entries {
			let entry = grouped
				.entry(&**icon)
				.or_default();
			entry.push((*style, &**suffix));
		}

		grouped
	};

	let mut grouped_by_style = grouped_by_style.into_iter().collect::<Vec<_>>();
	grouped_by_style.sort();

	let mut grouped_by_icon = grouped_by_icon.into_iter().collect::<Vec<_>>();
	grouped_by_icon.sort();

	let style = {
		let mut style = Vec::new();
		style.push("#[cfg(feature = \"str\")]\npub mod style {".into());

		for (s, icons) in grouped_by_style {
			style.push(format!("\tpub mod {s} {{"));

			for (i, suffix) in icons {
				let i_uppername = i.chars()
					.map(|c| if c == '-' { '_' } else { c })
					.flat_map(|c| c.to_uppercase())
					.collect::<String>();
				style.push(format!("\t\tpub const {i_uppername}: &str = include_str!(\"../{ROOT}/{s}/{i}{suffix}\");"));
			}

			style.push("\t}".into());
		}

		style.push("}".into());

		style
	};

	let icon = {
		let mut icon = Vec::new();
		icon.push("#[cfg(feature = \"str\")]\npub mod icon {".into());

		for (i, style) in grouped_by_icon {
			let i_underscored = i.chars()
				.map(|c| if c == '-' { '_' } else { c })
				.collect::<String>();
			icon.push(format!("\tpub mod {i_underscored} {{"));

			for (s, suffix) in style {
				let s_uppercase = s.to_uppercase();
				icon.push(format!("\t\tpub const {s_uppercase}: &str = include_str!(\"../{ROOT}/{s}/{i}{suffix}\");"));
			}

			icon.push("\t}".into());
		}

		icon.push("}".into());

		icon
	};

	let heading = [String::from("// Autogenerated")];
	let mods = [
		"pub mod util;"
	].map(Into::into);
	let newline = [""].map(Into::into);

	let file = fs::OpenOptions::new()
		.write(true)
		.truncate(true)
		// running in the scripts dir
		.open("../src/lib.rs")
		.unwrap();
	let mut file = BufWriter::with_capacity(1024 * 1024, file);

	heading
		.into_iter()
		.chain(newline.clone())
		.chain(mods)
		.chain(newline.clone())
		.chain(style)
		.chain(newline.clone())
		.chain(icon)
		.for_each(|line| {
			file.write_all(line.as_bytes()).unwrap();
			file.write_all(b"\n").unwrap();
		});
}

struct IconMap {
	map: BTreeMap<String, IconSet>
}

impl IconMap {
	fn read(
		// relative from scripts/ and src/ are the same so we only need one
		asset_path: &str
	) -> Self {
		let mut this = Self { map: BTreeMap::new() };
		let mut styles = fs::read_dir(asset_path)
			.unwrap()
			.map(|dirent| dirent.unwrap().file_name().to_str().unwrap().to_owned())
			.collect::<Vec<_>>();
		styles.sort_unstable();

		let mut suffix_map = SuffixMap::new();

		for style in styles {
			let mut dir_path = String::new();
			dir_path.reserve(asset_path.len() + 1 + style.len());
			dir_path.push_str(asset_path);
			#[expect(clippy::single_char_add_str)]
			dir_path.push_str("/");
			dir_path.push_str(&style);

			let suffix = suffix_map.get_suffix(&style);

			let icons = fs::read_dir(&*dir_path)
				.unwrap()
				.map(|dirent| dirent.unwrap().file_name().to_str().unwrap().to_owned())
				.map(|filename| filename.strip_suffix(suffix).unwrap().to_owned())
				.collect::<Vec<_>>();

			for icon in icons {
				let mut include_path = dir_path.clone();
				include_path.reserve(1 + icon.len() + suffix.len());
				#[expect(clippy::single_char_add_str)]
				include_path.push_str("/");
				include_path.push_str(&icon);
				include_path.push_str(suffix);

				let raw_svg = fs::read_to_string(&*include_path).unwrap();
				let data = IconData::parse(&raw_svg);

				let icon_entry = this.map.entry(icon).or_default();
				let icon_entry = match &*style {
					"bold" => { &mut icon_entry.bold }
					"duotone" => { &mut icon_entry.duotone }
					"fill" => { &mut icon_entry.fill }
					"light" => { &mut icon_entry.light }
					"regular" => { &mut icon_entry.regular }
					"thin" => { &mut icon_entry.thin }
					_ => { panic!("new icon variant introduced?") }
				};
				assert!(icon_entry.is_none());

				*icon_entry = Some(Icon {
					include_path,
					raw_svg,
					data
				});
			}
		}

		this
	}
}

#[derive(Default)]
struct IconSet {
	bold: Option<Icon>,
	duotone: Option<Icon>,
	fill: Option<Icon>,
	light: Option<Icon>,
	regular: Option<Icon>,
	thin: Option<Icon>,
}

struct Icon {
	include_path: String,
	raw_svg: String,
	data: IconData
}

struct IconData {
	pub path_d: String,
	pub path_d_duotone: Option<String>
}

impl IconData {
	fn parse(icon: &str) -> Self {
		// todo currently does not parse duotone
		let parsed = XmlDocument::parse(icon).expect("invalid icon");

		let root = parsed.root();
		assert_eq!(root.tag_name().name(), "", "sanity check");

		let mut root_children = root.children();
		let svg = root_children.next().expect("icon must have root item");
		assert!(svg.is_element(), "root item must be an element");
		assert_eq!(svg.tag_name().name(), "svg", "root element must be svg");
		assert_eq!(svg.tag_name().namespace(), Some("http://www.w3.org/2000/svg"), "missing svg xmlns");
		assert_eq!(svg.attributes().len(), 2, "extra attrs in svg tag found");
		assert_eq!(svg.attribute("viewBox"), Some("0 0 256 256"), "must have viewBox attr");
		assert_eq!(svg.attribute("fill"), Some("currentColor"), "must have fill attr");
		assert!(root_children.next().is_none(), "must have only one root element");

		let mut svg_children = svg.children();
		let path = svg_children.next().expect("svg must have at least one child");
		assert!(path.is_element(), "svg child must be element");
		assert_eq!(path.tag_name().name(), "path", "svg child must be path tag");
		assert_eq!(path.tag_name().namespace(), Some("http://www.w3.org/2000/svg"), "svg child path should have svg xmlns");
		assert!(!path.has_children(), "svg child path should have no children");

		let mut path_d = path.attribute("d").expect("path d attr must exist").into();
		let mut path_d_duotone = None;

		match path.attributes().len() {
			1 => {
				// other
			}
			2 => {
				// duotone, need special handling
				assert_eq!(path.attribute("opacity"), Some("0.2"), "first path in duotone icon must have opacity attr");
				path_d_duotone = Some(mem::take(&mut path_d));
				let path = svg_children.next().expect("svg must have two children in duotone icon");
				assert!(path.is_element(), "svg child 2 must be element");
				assert_eq!(path.tag_name().name(), "path", "svg child 2 must be path tag");
				assert_eq!(path.tag_name().namespace(), Some("http://www.w3.org/2000/svg"), "svg child 2 path should have svg xmlns");
				assert!(!path.has_children(), "svg child path 2 should have no children");
				assert_eq!(path.attributes().len(), 1, "extra attrs in path tag found");
				path_d = path.attribute("d").expect("path d attr must exist").into();
			}
			_ => {
				// 0 can't happen, we just got an attribute before this match statement
				panic!("extra attrs in path tag found");
			}
		}
		assert!(svg_children.next().is_none(), "svg should have only one child");

		Self { path_d, path_d_duotone }
	}
}

// is this a meaningful optimisation? probably not. only probably saves
// a few thousand allocations, it's not much (/not s)
struct SuffixMap {
	inner: Vec<(String, String)>
}

impl SuffixMap {
	fn new() -> Self {
		Self { inner: Vec::with_capacity(6) }
	}

	fn get_suffix(&mut self, style: &str) -> &str {
		let suffix = self.inner
			.iter()
			.find(|(s, _)| &**s == style)
			.map(|(_, suffix)| suffix);
		if let Some(suffix) = suffix {
			return suffix
		}

		let suffix = if style == "regular" {
			".svg".into()
		} else {
			format!("-{style}.svg")
		};
		self.inner.push((style.into(), suffix));

		self.get_suffix(style)
	}
}
